"""The controller accepts the same interface for MQTT and actual Matter."""
from typing import Protocol, Iterable, Any


class DeviceTransport(Protocol):
    @property
    def connected(self) -> bool: ...
    def start(self) -> None: ...
    def stop(self) -> None: ...
    def publish(self, kind: str, item: Any) -> bool: ...
    def drain(self) -> Iterable[tuple[str, Any]]: ...
